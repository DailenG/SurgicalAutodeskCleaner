function Test-SACPendingReboot {
    <#
    .SYNOPSIS
        Checks if there is a pending system reboot.
    .DESCRIPTION
        Inspects common registry keys for pending reboot flags. The individual conditions
        that tripped are published in $script:SACPendingRebootReasons so callers can tell a
        real servicing reboot from merely queued file renames, which are not the same risk.
    #>
    $Reasons = @()

    # Key 1: Component Based Servicing reboot pending
    if (Test-Path "HKLM:\SOFTWARE\Microsoft\Windows\CurrentVersion\Component Based Servicing\RebootPending") {
        $Reasons += 'Component Based Servicing: RebootPending'
    }

    # Key 2: Windows Update auto update reboot required
    if (Test-Path "HKLM:\SOFTWARE\Microsoft\Windows\CurrentVersion\WindowsUpdate\Auto Update\RebootRequired") {
        $Reasons += 'Windows Update: RebootRequired'
    }

    # Key 3: PendingFileRenameOperations
    $pfro = Get-ItemProperty -Path "HKLM:\SYSTEM\CurrentControlSet\Control\Session Manager" -Name "PendingFileRenameOperations" -ErrorAction SilentlyContinue
    if ($pfro -and $pfro.PendingFileRenameOperations) {
        # Check if the array actually contains items
        $pfroCount = @($pfro.PendingFileRenameOperations).Count
        if ($pfroCount -gt 0) {
            $Reasons += "Session Manager: $pfroCount queued PendingFileRenameOperations"
        }
    }

    # Key 4: UpdateExeVolatile
    $volatile = Get-ItemProperty -Path "HKLM:\SOFTWARE\Microsoft\Updates" -Name "UpdateExeVolatile" -ErrorAction SilentlyContinue
    if ($volatile -and $volatile.UpdateExeVolatile -ne 0) {
        $Reasons += 'Microsoft\Updates: UpdateExeVolatile'
    }

    $script:SACPendingRebootReasons = @($Reasons)
    return ($Reasons.Count -gt 0)
}

function Get-SACPendingRebootReason {
    <#
    .SYNOPSIS
        Returns the conditions recorded by the most recent Test-SACPendingReboot call.
    #>
    return @($script:SACPendingRebootReasons)
}
